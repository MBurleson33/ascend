"""Regenerates sw.js. Run after changing index.html or any asset:  python3 tools/build_sw.py"""
import glob, hashlib, json, os
os.chdir(os.path.join(os.path.dirname(__file__), '..'))
files = ['index.html', 'manifest.webmanifest'] + sorted(f for f in glob.glob('icons/*.png') if 'source' not in f) + sorted(glob.glob('assets/*.webp')) + sorted(glob.glob('assets/*/*.webp'))
h = hashlib.sha1()
for f in files: h.update(f.encode()); h.update(open(f, 'rb').read())
version = 'ascend-' + h.hexdigest()[:10]
core = ['./'] + ['./' + f for f in files]
sw = f"""// Generated by tools/build_sw.py. Do not edit by hand.
const V = '{version}', FONTS = 'ascend-fonts';
const CORE = {json.dumps(core, indent=1)};
self.addEventListener('install', e => {{ e.waitUntil(caches.open(V).then(c => c.addAll(CORE))); }});
self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== V && k !== FONTS).map(k => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener('message', e => {{ if (e.data === 'SKIP_WAITING') self.skipWaiting(); }});
self.addEventListener('fetch', e => {{
  const r = e.request; if (r.method !== 'GET') return;
  const u = new URL(r.url);
  if (r.mode === 'navigate') {{
    e.respondWith(fetch(r).then(res => {{ const cp = res.clone(); caches.open(V).then(c => c.put('./index.html', cp)); return res; }}).catch(() => caches.match('./index.html')));
    return;
  }}
  if (u.origin === location.origin) {{
    e.respondWith(caches.match(r, {{ignoreSearch: true}}).then(hit => hit || fetch(r).then(res => {{ if (res.ok) {{ const cp = res.clone(); caches.open(V).then(c => c.put(r, cp)); }} return res; }})));
    return;
  }}
  if (/fonts\\.(googleapis|gstatic)\\.com$/.test(u.host)) {{
    e.respondWith(caches.open(FONTS).then(c => c.match(r).then(hit => {{
      const net = fetch(r).then(res => {{ c.put(r, res.clone()); return res; }}).catch(() => hit);
      return hit || net;
    }})));
  }}
}});
"""
open('sw.js', 'w').write(sw)
print(version, len(core), 'files')
